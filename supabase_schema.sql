-- 1. Enable UUID Extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Public User Profiles Table (Linked to Supabase Auth)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    display_name TEXT NOT NULL,
    avatar_url TEXT,
    provider TEXT NOT NULL DEFAULT 'email',
    spotify_id TEXT,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()))::BIGINT,
    updated_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()))::BIGINT
);

-- 3. User Favorites Table (Cloud Backed)
CREATE TABLE IF NOT EXISTS public.user_favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    video_id TEXT NOT NULL,
    track_json JSONB NOT NULL,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()))::BIGINT,
    UNIQUE(user_id, video_id)
);

CREATE INDEX IF NOT EXISTS idx_favorites_user ON public.user_favorites(user_id);
CREATE INDEX IF NOT EXISTS idx_favorites_video ON public.user_favorites(video_id);

-- 4. User Followed Artists Table (Cloud Backed)
CREATE TABLE IF NOT EXISTS public.user_followed_artists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    artist_name TEXT NOT NULL,
    artist_browse_id TEXT,
    avatar_url TEXT,
    subscribers TEXT,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()))::BIGINT,
    UNIQUE(user_id, artist_name)
);

CREATE INDEX IF NOT EXISTS idx_followed_artists_user ON public.user_followed_artists(user_id);

-- 5. User Playlists Table (Both Custom and Spotify Playlist References)
CREATE TABLE IF NOT EXISTS public.user_playlists (
    id TEXT PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    description TEXT,
    cover_url TEXT,
    source TEXT NOT NULL DEFAULT 'custom', -- 'custom' or 'spotify'
    spotify_playlist_id TEXT,             -- Lightweight reference: tracks fetched on demand
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()))::BIGINT,
    updated_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()))::BIGINT
);

CREATE INDEX IF NOT EXISTS idx_playlists_user ON public.user_playlists(user_id);

-- 6. Custom Playlist Tracks Table (Tracks for user-created custom playlists)
-- Note: Spotify playlists do not store individual tracks here; they are loaded via link
CREATE TABLE IF NOT EXISTS public.user_playlist_tracks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id TEXT NOT NULL REFERENCES public.user_playlists(id) ON DELETE CASCADE,
    video_id TEXT NOT NULL,
    track_json JSONB NOT NULL,
    position INTEGER NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()))::BIGINT,
    UNIQUE(playlist_id, video_id)
);

CREATE INDEX IF NOT EXISTS idx_playlist_tracks_pid ON public.user_playlist_tracks(playlist_id);

-- ==============================================================================
-- Row Level Security (RLS) Policies
-- ==============================================================================

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_favorites ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_followed_artists ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_playlists ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_playlist_tracks ENABLE ROW LEVEL SECURITY;

-- Profiles: Public can view, only user can update
CREATE POLICY "Public profiles are viewable by everyone" 
ON public.profiles FOR SELECT USING (true);

CREATE POLICY "Users can insert their own profile" 
ON public.profiles FOR INSERT WITH CHECK (auth.uid() = id);

CREATE POLICY "Users can update their own profile" 
ON public.profiles FOR UPDATE USING (auth.uid() = id);

-- Favorites: User-scoped
CREATE POLICY "Users can view their own favorites" 
ON public.user_favorites FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Users can add their own favorites" 
ON public.user_favorites FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update their own favorites" 
ON public.user_favorites FOR UPDATE USING (auth.uid() = user_id);

CREATE POLICY "Users can delete their own favorites" 
ON public.user_favorites FOR DELETE USING (auth.uid() = user_id);

-- Followed Artists: User-scoped
CREATE POLICY "Users can view their followed artists" 
ON public.user_followed_artists FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Users can follow artists" 
ON public.user_followed_artists FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update their own followed artists" 
ON public.user_followed_artists FOR UPDATE USING (auth.uid() = user_id);

CREATE POLICY "Users can unfollow artists" 
ON public.user_followed_artists FOR DELETE USING (auth.uid() = user_id);

-- Playlists: User-scoped
CREATE POLICY "Users can view their own playlists" 
ON public.user_playlists FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Users can create their own playlists" 
ON public.user_playlists FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update their own playlists" 
ON public.user_playlists FOR UPDATE USING (auth.uid() = user_id);

CREATE POLICY "Users can delete their own playlists" 
ON public.user_playlists FOR DELETE USING (auth.uid() = user_id);

-- Custom Playlist Tracks: User-scoped via playlist ownership
CREATE POLICY "Users can view tracks in their playlists" 
ON public.user_playlist_tracks FOR SELECT 
USING (EXISTS (SELECT 1 FROM public.user_playlists WHERE id = playlist_id AND user_id = auth.uid()));

CREATE POLICY "Users can add tracks to their playlists" 
ON public.user_playlist_tracks FOR INSERT 
WITH CHECK (EXISTS (SELECT 1 FROM public.user_playlists WHERE id = playlist_id AND user_id = auth.uid()));

CREATE POLICY "Users can update tracks in their playlists" 
ON public.user_playlist_tracks FOR UPDATE 
USING (EXISTS (SELECT 1 FROM public.user_playlists WHERE id = playlist_id AND user_id = auth.uid()));

CREATE POLICY "Users can delete tracks from their playlists" 
ON public.user_playlist_tracks FOR DELETE 
USING (EXISTS (SELECT 1 FROM public.user_playlists WHERE id = playlist_id AND user_id = auth.uid()));

-- ==============================================================================
-- Auto-create Profile Trigger upon Supabase Email Signup
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, email, display_name, avatar_url, provider)
    VALUES (
        NEW.id,
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'displayName', NEW.raw_user_meta_data->>'full_name', split_part(NEW.email, '@', 1)),
        NEW.raw_user_meta_data->>'avatar_url',
        COALESCE(NEW.raw_app_meta_data->>'provider', 'email')
    )
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
